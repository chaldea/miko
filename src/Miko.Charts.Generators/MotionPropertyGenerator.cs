using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Miko.Charts.Generators;

/// <summary>
/// Turns each <c>[MotionProperty] public partial T Name { get; set; }</c> into an animatable property:
/// a backing <c>MotionProperty</c>, the static <c>NameProperty</c> definition and the per-type
/// <c>PropertyDefinitions</c> table that lets transitions be set by name.
/// </summary>
[Generator]
public sealed class MotionPropertyGenerator : IIncrementalGenerator
{
    private const string MotionPropertyAttribute = "LiveChartsCore.Generators.MotionPropertyAttribute";

    private static readonly SymbolDisplayFormat s_nameOnly = new(
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameOnly,
        genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters);

    private static readonly SymbolDisplayFormat s_qualifiedNoGenerics = new(
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        genericsOptions: SymbolDisplayGenericsOptions.None);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var groups = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                MotionPropertyAttribute,
                predicate: static (node, _) => node is PropertyDeclarationSyntax,
                transform: static (ctx, _) => GetProperty(ctx))
            .Where(static p => p is not null)
            .Collect()
            .Select(static (props, _) => props
                .GroupBy(p => p!.Property.ContainingType, SymbolEqualityComparer.Default)
                .ToList());

        context.RegisterSourceOutput(groups, static (spc, all) =>
        {
            foreach (var group in all)
            {
                if (group.Key is not INamedTypeSymbol type) continue;

                foreach (var item in group)
                {
                    spc.AddSource(
                        $"{type.Name}.{item!.Property.Name}.g.cs".Replace('<', '_').Replace('>', '_'),
                        SourceText.From(GetPropertySource(item), Encoding.UTF8));
                }

                spc.AddSource(
                    $"{type.Name}.g.cs".Replace('<', '_').Replace('>', '_'),
                    SourceText.From(GetTypeSource(type, group), Encoding.UTF8));
            }
        });
    }

    private static MotionPropertyInfo? GetProperty(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not IPropertySymbol symbol) return null;

        var explicitAccessors = false;
        foreach (var attribute in ctx.Attributes)
        {
            foreach (var arg in attribute.NamedArguments)
            {
                if (arg.Key == "HasExplicitAcessors") explicitAccessors = (bool?)arg.Value.Value ?? true;
            }
        }

        return new MotionPropertyInfo(symbol, explicitAccessors);
    }

    private static string GetPropertySource(MotionPropertyInfo target)
    {
        var property = target.Property;
        var name = property.Name;
        var type = property.ContainingType;
        var declaringType = type.ToDisplayString(s_nameOnly);
        var propertyType = property.Type.ToDisplayString();
        var sanitized = property.Type.IsReferenceType && propertyType.EndsWith("?")
            ? propertyType.Substring(0, propertyType.Length - 1)
            : propertyType;

        var getter = property.GetMethod is null
            ? string.Empty
            : target.HasExplicitAccessors ? "get;" : $"get => _{name}MotionProperty.GetMovement(this);";
        var setter = property.SetMethod is null
            ? string.Empty
            : target.HasExplicitAccessors
                ? "set;"
                : $"set {{ _{name}MotionProperty.SetMovement(value, this); On{name}Changed(value); }}";

        return $@"// <auto-generated>
//     Generated by Miko.Charts.Generators, do not edit.
// </auto-generated>

#nullable enable

namespace {type.ContainingNamespace};

{Accessibility(type.DeclaredAccessibility)} partial class {declaringType}
{{
    /// <summary>The <see cref=""{name}""/> property definition.</summary>
    public static readonly LiveChartsCore.Motion.PropertyDefinition {name}Property = new(
        propertyName:   ""{name}"",
        propertyType:   typeof({sanitized}),
        getter:         (g)     =>   (({declaringType})g).{name},
        setter:         (g, v)  =>   (({declaringType})g).{name} = v is {sanitized} s ? s : (({declaringType})g)._{name}MotionProperty.DefaultValue,
        motionGetter:   (g)     =>   (({declaringType})g)._{name}MotionProperty);

    private readonly {MotionPropertyType(property.Type)} _{name}MotionProperty = new();

    /// <summary>The <see cref=""{name}""/> motion property: assigning it animates towards the new value.</summary>
    {Accessibility(property.DeclaredAccessibility)} partial {property.Type.ToDisplayString()} {name}
    {{
        {getter}
        {setter}
    }}

    partial void On{name}Changed({property.Type.ToDisplayString()} value);
}}
";
    }

    private static string GetTypeSource(INamedTypeSymbol type, IGrouping<ISymbol?, MotionPropertyInfo?> group)
    {
        var baseType = type.BaseType;
        if (baseType is null)
            return $"// {type.Name} must derive from Animatable.";

        var entries = new StringBuilder();
        foreach (var item in group)
            entries.AppendLine($@"            [""{item!.Property.Name}""] = {item.Property.Name}Property,");

        return $@"// <auto-generated>
//     Generated by Miko.Charts.Generators, do not edit.
// </auto-generated>

namespace {type.ContainingNamespace};

{Accessibility(type.DeclaredAccessibility)} partial class {type.ToDisplayString(s_nameOnly)}
{{
    /// <summary>The motion property definitions declared by this type and its bases.</summary>
    public static new System.Collections.Generic.Dictionary<string, LiveChartsCore.Motion.PropertyDefinition> PropertyDefinitions {{ get; }} =
        Merge(new()
        {{
{entries}        }},
        {baseType.ToDisplayString(s_qualifiedNoGenerics)}.PropertyDefinitions);

    /// <inheritdoc />
    protected override System.Collections.Generic.Dictionary<string, LiveChartsCore.Motion.PropertyDefinition> GetPropertyDefinitions() => PropertyDefinitions;
}}";
    }

    private static string Accessibility(Accessibility accessibility) => accessibility switch
    {
        Microsoft.CodeAnalysis.Accessibility.Public => "public",
        Microsoft.CodeAnalysis.Accessibility.Private => "private",
        Microsoft.CodeAnalysis.Accessibility.Internal => "internal",
        Microsoft.CodeAnalysis.Accessibility.Protected => "protected",
        Microsoft.CodeAnalysis.Accessibility.ProtectedAndInternal => "private protected",
        Microsoft.CodeAnalysis.Accessibility.ProtectedOrInternal => "protected internal",
        _ => "internal",
    };

    private static string MotionPropertyType(ITypeSymbol type) => type.ToDisplayString() switch
    {
        "float" => "LiveChartsCore.Motion.FloatMotionProperty",
        "double" => "LiveChartsCore.Motion.DoubleMotionProperty",
        "double?" => "LiveChartsCore.Motion.NullableDoubleMotionProperty",
        "LiveChartsCore.Drawing.LvcColor" => "LiveChartsCore.Motion.ColorMotionProperty",
        "LiveChartsCore.Drawing.LvcPoint" => "LiveChartsCore.Motion.PointMotionProperty",
        "LiveChartsCore.Drawing.LvcSize" => "LiveChartsCore.Motion.SizeMotionProperty",
        "LiveChartsCore.Drawing.Padding" => "LiveChartsCore.Motion.PaddingMotionProperty",
        "LiveChartsCore.Painting.Paint" or "LiveChartsCore.Painting.Paint?" => "LiveChartsCore.Motion.PaintMotionProperty",
        "LiveChartsCore.Drawing.LvcDropShadow" or "LiveChartsCore.Drawing.LvcDropShadow?" => "LiveChartsCore.Motion.DropShadowMotionProperty",
        _ => "UnsupportedMotionPropertyType",
    };

    private sealed class MotionPropertyInfo
    {
        public MotionPropertyInfo(IPropertySymbol property, bool hasExplicitAccessors)
        {
            Property = property;
            HasExplicitAccessors = hasExplicitAccessors;
        }

        public IPropertySymbol Property { get; }

        public bool HasExplicitAccessors { get; }
    }
}

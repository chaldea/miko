using Miko.Native;
using Miko.Windowing;
using Miko.Windowing.Video;
using Anime;

namespace Anime.Desktop;

public static class Program
{
    [STAThread]
    public static void Main(string[] args)
    {
        var context = App.CreateContext(builder =>
        {
            builder.UseSystemVideo();
            // The frame probe closes the window through the native host context when it finishes.
            if (DesktopFrameProbe.IsRequested)
                builder.Services.AddMikoNative();
        });

        // Hot reload is wired up inside the shared app assembly, where the
        // handler is generated by Miko.Razor.Compiler.
        App.InitializeHotReload(context);

        DesktopFrameProbe.StartIfRequested(context);
        context.RunDesktop();
    }
}
